async page => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({width:1280,height:1000});
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('oche.301.v1')));
  const hit = code => page.locator('.board-segment[data-inner="false"][data-code="' + code + '"]').click();
  const close = () => page.locator('#dialog [data-action="close-dialog"]').click();
  const next = () => page.locator('.board-turn-callout [data-action="next-player"]').click();
  const openRewards = async () => {
    await page.locator('[data-tab="players"]').first().click();
    await page.locator('.profile [data-action="achievements"]').first().click();
  };
  await hit('T20'); await hit('T20');
  assert(await page.locator('#achievement-notice').isHidden(), 'No unlock from an incomplete visit');
  await hit('T20');
  assert(await page.locator('#achievement-notice').isVisible(), 'Maximum unlock notification');
  assert(await page.locator('#fx-host [data-victory-pose="mic-drop"]').count() === 1, '180 gets the newly unlocked mic drop');
  await page.locator('.console-actions [data-action="undo"]').click();
  assert(await page.locator('#achievement-notice').isHidden(), 'Undo clears notification');
  assert(await page.locator('#fx-host [data-victory-pose]').count() === 0, 'Undo cancels pose');
  await hit('T20');
  await page.locator('#achievement-notice [data-action="achievements"]').click();
  assert(await page.locator('[data-action="equip-achievement"]').isEnabled(), 'Earned reward is equipable');
  await page.locator('[data-action="equip-achievement"]').click();
  await page.locator('#reward-pose').selectOption('mic-drop');
  assert((await saved()).players[0].rewards.stamp === 'maximum', 'Stamp equipment saves');
  await page.locator('[data-action="preview-victory-pose"]').click();
  assert(await page.locator('#reward-pose-preview [data-victory-pose="mic-drop"]').count() === 1, 'Equipped pose preview');
  await page.locator('[data-action="pin-achievement"]').click();
  assert((await saved()).players[0].rewards.pins.length === 0, 'Unpin all stays empty');
  await page.locator('[data-action="pin-achievement"]').click();
  await page.locator('[data-action="preview-achievement"][data-reward="ice"]').click();
  assert(await page.locator('[data-action="equip-achievement"]').isDisabled(), 'Locked reward cannot equip');
  assert(await page.locator('#reward-pose option[value="bow"]').isDisabled(), 'Locked pose cannot equip');
  await close();
  assert(await page.locator('.arcade-player .name-maximum').count() === 1, 'Equipment appears in the live lineup');
  await next();
  for (let i=0;i<3;i++) await page.locator('.console-actions [data-code="MISS"]').click();
  await next();
  await hit('T20'); await hit('S11'); await hit('BULL');
  assert(await page.locator('.checkout-stamp').count() === 1, 'Winning visit receives a stamp');
  const firstFinish=await saved();
  assert(firstFinish.matches.find(m=>m.id===firstFinish.currentId).visits.at(-1).stamp === 'maximum', 'Winning stamp is stored');
  assert(await page.locator('#fx-host [data-victory-pose="mic-drop"]').count() === 1, 'Explicit pose overrides automatic bow');
  await openRewards();
  await page.locator('[data-action="preview-achievement"][data-reward="gold"]').click();
  await page.locator('[data-action="equip-achievement"]').click();
  assert(await page.locator('.achievement-source').count() === 1, 'Medal has earning match evidence');
  await close();
  assert(await page.locator('.medal-shelf .shelf-medal').count() >= 1, 'Medal shelf on profiles');
  await page.locator('[data-tab="match"]').first().click();
  assert(await page.locator('.checkout-stamp').getAttribute('title') === 'Maximum · Player 1', 'Changing equipment does not rewrite past stamps');
  await page.locator('.winner-panel [data-action="undo"]').click();
  assert(await page.locator('.checkout-stamp').count() === 0, 'Undo removes the checkout stamp');
  assert(await page.locator('.arcade-player .name-gold').count() === 0, 'Undo revokes ineligible appearance');

  // Fixture with all six achievements and an unfinished solo visit.
  const base = await saved(), profile = base.players[0];
  const visit = (total, extra={}) => ({total,darts:3,bust:false,double:false,...extra});
  let serial=0;
  const game = (players, visits, extra={}) => ({id:'reward-game-'+serial++,startedAt:'2026-09-10T10:00:00Z',players,visits:visits.map(v=>typeof v==='number'?visit(v):v),out:'straight',bestOf:1,finishMode:players.length>2?'placements':'first',abandoned:false,pending:[],awaitingNext:false,...extra});
  const soloPlayers = [{id:profile.id,name:profile.name,avatar:profile.avatar}];
  base.matches = Array.from({length:50},()=>game(soloPlayers,[180,121]));
  base.matches.push(game(base.players.map(p=>({id:p.id,name:p.name,avatar:p.avatar})),[0,180,180,0,121]));
  for(let i=0;i<25;i++) base.matches.push(game(soloPlayers,[visit(50,{darts:1,hits:['BULL'],double:true})],{abandoned:true}));
  const active = game(soloPlayers,[],{pending:[]});base.matches.push(active);base.currentId=active.id;
  profile.name='Kelvin with a long player name';
  profile.rewards={name:'gold',background:'bull',frame:'maximum',title:'ice',stamp:'regular',pose:'bow',pins:['maximum','ice','regular']};
  await page.evaluate(d=>localStorage.setItem('oche.301.v1',JSON.stringify(d)),base);
  await page.reload();
  assert(await page.locator('.arcade-player .name-gold').count() === 1, 'Equipment survives reload');
  await openRewards();
  assert((await page.locator('#dialog .dialog-body>p').first().textContent()).includes('6 of 6'), 'All six unlock from historical records');
  await page.locator('[data-action="preview-achievement"][data-reward="gold"]').click();
  await page.locator('[data-action="pin-achievement"]').click();
  assert((await saved()).players[0].rewards.pins.length===3, 'Shelf capped at three');
  await page.locator('[data-action="preview-achievement"][data-reward="maximum"]').click();
  await page.locator('[data-action="pin-achievement"]').click();
  await page.locator('[data-action="preview-achievement"][data-reward="gold"]').click();
  await page.locator('[data-action="pin-achievement"]').click();
  assert((await saved()).players[0].rewards.pins.includes('gold'), 'Pin a new favorite after unpinning');
  await page.locator('#reward-name').selectOption('comeback');
  await page.locator('#reward-background').selectOption('ice');
  await page.locator('#reward-pose').selectOption('salute');
  await page.locator('[data-action="preview-victory-pose"]').click();
  assert(await page.locator('#reward-pose-preview [data-victory-pose="salute"]').count()===1, 'Salute preview');
  await page.locator('#reward-pose').selectOption('bow');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.locator('[data-action="preview-victory-pose"]').click();
  assert(await page.locator('#reward-pose-preview .dance-upper').evaluate(el=>getComputedStyle(el).animationName)==='none','Reduced-motion pose is static');
  for(const width of [1280,768,390,320]){
    await page.setViewportSize({width,height:900});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No page overflow '+width);
    assert(await page.locator('#dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),'No dialog overflow '+width);
  }
  await page.locator('#dialog').screenshot({path:'.playwright-cli/achievements-live-mobile.png'});
  await page.setViewportSize({width:1440,height:1100});
  await page.locator('#dialog').screenshot({path:'.playwright-cli/achievements-live-equipped.png'});
  await close();
  await page.locator('[data-tab="match"]').first().click();
  await hit('T20'); await hit('T20'); await hit('T20'); await next();
  await hit('T20'); await hit('S11'); await hit('BULL');
  const snapshot=await saved(),last=snapshot.matches.find(m=>m.id===snapshot.currentId).visits.at(-1);
  assert(last.stamp==='regular'&&Number.isFinite(Date.parse(last.recordedAt)),'Checkout stores equipped stamp and earning date');
  assert(await page.locator('.checkout-stamp').getAttribute('title')==='Club Regular · Player 1','Historical match keeps its player name');
  assert(await page.locator('#fx-host [data-victory-pose="bow"]').count()===1,'Live checkout uses bow');
  const downloadPromise=page.waitForEvent('download');
  await page.locator('.footer-links [data-action="export"]').click();
  const download=await downloadPromise;
  const backupPath=await download.path();
  await page.locator('#import-file').setInputFiles(backupPath);
  await page.locator('[data-action="confirm-import"]').click();
  assert((await saved()).players[0].rewards.name==='comeback','Backup restores cosmetic equipment');
  assert((await saved()).players[0].rewards.pins.length===3,'Backup restores medal pins');
  assert(await page.locator('.checkout-stamp').count()===1,'Backup restores recorded stamp');
  assert(errors.length===0,'No browser errors: '+errors.join(', '));
  return 'Live unlocks, poses, stamps, eligibility, pins, reload, backup, responsive layout, and reduced motion passed.';
}
