async page => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  await page.reload();
  await page.setViewportSize({ width: 375, height: 812 });
  await page.locator('[data-action="new-match"]').click();
  const order = () => page.locator('#player-choices [data-order-id]').evaluateAll(els => els.map(el => el.dataset.orderId));
  const before = await order();
  assert(before.length === 8, 'Run playing-order-check first to prepare eight players');
  await page.locator('#player-choices').evaluate(el => el.scrollTop = 0);
  const grip = await page.locator('[data-reorder-id]').first().boundingBox();
  const second = await page.locator('[data-order-id]').nth(1).boundingBox();
  const x = grip.x + grip.width / 2, y = grip.y + grip.height / 2;
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled', { enabled: true });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: second.y + second.height * .75 }] });
  await page.waitForTimeout(120);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert((await order())[1] === before[0], 'Native touch drag must move the first player down');
  assert(await page.locator('.lineup-ghost').count() === 0, 'Drop must remove the floating row');
  const touchOrder = await order();
  await page.locator('#player-choices').evaluate(el => el.scrollTop = 0);
  const start = await page.locator('[data-reorder-id]').first().boundingBox();
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
  await page.mouse.down();
  await page.mouse.move(x, second.y + second.height * .75, { steps: 5 });
  await page.waitForTimeout(100);
  await page.keyboard.press('Escape');
  await page.mouse.up();
  assert(JSON.stringify(await order()) === JSON.stringify(touchOrder), 'Escape must restore the original order');
  assert(await page.locator('#dialog').isVisible(), 'Escape during drag must leave setup open');
  await page.locator('#player-choices').evaluate(el => el.scrollTop = 0);
  const first = await page.locator('[data-reorder-id]').first().boundingBox();
  const list = await page.locator('#player-choices').boundingBox();
  await page.mouse.move(first.x + first.width / 2, first.y + first.height / 2);
  await page.mouse.down();
  await page.mouse.move(x, list.y + list.height - 4, { steps: 8 });
  await page.waitForTimeout(900);
  await page.mouse.up();
  assert((await order())[7] === touchOrder[0], 'Dragging at the edge must scroll to the last player');
  await cdp.detach();
  console.log('Touch drag, cancellation, cleanup, and eight-player auto-scroll passed.');
}
